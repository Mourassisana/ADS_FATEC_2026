# Exercício 11: Receba o raio de uma circunferência. Calcule e mostre o comprimento da circunferência.

# 1. Recebe o raio da cincunferência
raio = float(input("Insira o raio da circunferência: "))

# 2. Atribua valor a Pi
pi = 3.1416

# 3. Calcula o comprimento da circunferência
comp = (2 * pi * raio)

#4. Exibe resultado
print(f"O comprimento da circunferência é: {comp:.2f}")